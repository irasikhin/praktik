// Package handbook generates HANDBOOK.md — a human-readable index of every
// skill, grouped by axis. It is a faithful port of scripts/gen-handbook.py and
// reproduces its output byte-for-byte, so `praktik handbook --check` is a drop-in
// CI gate against the committed file. The grouping helpers (Group, Order, Label,
// Summarize) are also reused by `praktik list`.
package handbook

import (
	"fmt"
	"sort"
	"strings"

	"github.com/irasikhin/praktik/internal/library"
)

// Order is the axis-group render order.
var Order = []string{"index", "proc", "flow", "tool", "lang", "build", "arch", "data", "framework", "ci", "other"}

// Label is the heading shown for each group.
var Label = map[string]string{
	"index":     "Index",
	"proc":      "Process — every project",
	"flow":      "Working methods",
	"tool":      "Tool how-tos",
	"lang":      "Language",
	"build":     "Build tool",
	"arch":      "Architecture",
	"data":      "Data stack",
	"framework": "Framework",
	"ci":        "CI host",
	"other":     "Other",
}

// triggerMarkers separate a description's summary from its "use when …" prose.
var triggerMarkers = []string{" Use when", " Use whenever", " Use at", " Use this", " Use the"}

const autoComment = "<!-- AUTO-GENERATED by praktik handbook — do not edit by hand. Regenerate: praktik handbook -->"

const introPara = "Human-readable index of every praktik skill, grouped by axis. The skill bodies " +
	"(`skills/<name>/SKILL.md`) **are** the conventions — this page is the entry point and table of " +
	"contents for people. Agents discover the same skills by their `description`; for adoption " +
	"mechanics and the axis model see [README](README.md) and the `praktik-index` skill."

// Group maps a metadata.axis value to its render group.
func Group(axis string) string {
	switch axis {
	case "index", "proc", "flow", "tool", "arch", "data", "framework", "ci":
		return axis
	}
	if strings.HasPrefix(axis, "lang-") {
		return "lang"
	}
	if strings.HasPrefix(axis, "build-") {
		return "build"
	}
	return "other"
}

// Summarize reduces a description to a one-line summary: the text before the
// "Use when …" trigger, else the first sentence.
func Summarize(description string) string {
	cut := -1
	for _, m := range triggerMarkers {
		if i := strings.Index(description, m); i != -1 && (cut == -1 || i < cut) {
			cut = i
		}
	}
	if cut != -1 {
		return strings.TrimRight(description[:cut], " .") + "."
	}
	if dot := strings.Index(description, ". "); dot != -1 {
		return strings.TrimSpace(description[:dot+1])
	}
	return strings.TrimSpace(description)
}

type row struct{ group, name, summary string }

// Generate renders the handbook and returns it with the number of skills.
func Generate(lib *library.Library) (string, int, error) {
	dirs, err := lib.Dirs()
	if err != nil {
		return "", 0, err
	}
	var rows []row
	for _, name := range dirs {
		s, ok, err := lib.ReadSkill(name)
		if err != nil {
			return "", 0, err
		}
		if !ok || !s.HasFront {
			continue
		}
		nm := s.FrontName
		if nm == "" {
			nm = name
		}
		rows = append(rows, row{Group(s.Axis), nm, Summarize(s.Description)})
	}
	sort.SliceStable(rows, func(i, j int) bool {
		gi, gj := orderIndex(rows[i].group), orderIndex(rows[j].group)
		if gi != gj {
			return gi < gj
		}
		return rows[i].name < rows[j].name
	})
	return render(rows), len(rows), nil
}

func orderIndex(g string) int {
	for i, o := range Order {
		if o == g {
			return i
		}
	}
	return len(Order)
}

func render(rows []row) string {
	groups := map[string]bool{}
	for _, r := range rows {
		groups[r.group] = true
	}
	var out []string
	out = append(out, "# praktik handbook\n")
	out = append(out, autoComment+"\n")
	out = append(out, introPara+"\n")
	out = append(out, fmt.Sprintf("_%d skills across %d axes._\n", len(rows), len(groups)))
	for _, group := range Order {
		var members []row
		for _, r := range rows {
			if r.group == group {
				members = append(members, r)
			}
		}
		if len(members) == 0 {
			continue
		}
		out = append(out, fmt.Sprintf("## %s\n", Label[group]))
		for _, m := range members {
			out = append(out, fmt.Sprintf("- **[%s](skills/%s/SKILL.md)** — %s", m.name, m.name, m.summary))
		}
		out = append(out, "")
	}
	return strings.TrimRight(strings.Join(out, "\n"), " \t\n\r\f\v") + "\n"
}
